const BASE_NAMES = { ashen: 'Ashen Crown', astral: 'Astral Oracle', iron: 'Iron Litany', bloodmoon: 'Blood Moon' };

function themeVariables() {
  const css = fs.readFileSync(path.join(root, 'app', 'css', 'themes.css'), 'utf8');
  const bases = Object.keys(BASE_NAMES),
    vals = {};
  bases.forEach(b => {
    const m = new RegExp('\\[data-theme="' + b + '"\\]\\{([^}]*)\\}').exec(css);
    if (!m) throw new Error('No variables found for ' + b + ' in themes.css');
    vals[b] = {};
    m[1].split(';').forEach(d => {
      const i = d.indexOf(':');
      if (i > 0) vals[b][d.slice(0, i).trim()] = d.slice(i + 1).trim();
    });
  });
  const cell = v => (v == null ? '' : '`' + v.replace(/\|/g, '\\|') + '`');
  const lines = [
    '# Theme variables',
    '',
    '<!-- Generated by scripts/make-modkit.js from app/css/themes.css. Do not edit by hand. -->',
    '',
    "These are the only variables a theme's `vars` may set. Anything you leave out comes from the theme's `base`.",
    'This table shows what each base uses, so you can see what you are changing.',
    '',
    '| Variable | Used for | ' + bases.map(b => BASE_NAMES[b] + ' (`' + b + '`)').join(' | ') + ' |',
    '| --- | --- | ' + bases.map(() => '---').join(' | ') + ' |',
  ];
  Object.keys(VAR_HELP).forEach(k =>
    lines.push('| `' + k + '` | ' + VAR_HELP[k] + ' | ' + bases.map(b => cell(vals[b][k])).join(' | ') + ' |')
  );
  lines.push(
    '',
    'Values may be colours, sizes or font lists, up to 200 characters. They may not load anything: no `url()`,',
    '`image-set()` or similar, and no `;`, `{`, `}`, `<`, `>`, `@` or backslashes.',
    ''
  );
  return lines.join('\n');
}

