function wheelsReference(FW) {
  const lines = [
    '# Wheels and built-in entries',
    '',
    "<!-- Generated by scripts/make-modkit.js from the game's data. Do not edit by hand. -->",
    '',
    'The wheel keys you can add entries to, and every built-in entry with its slice size (`w`) and codes (`dsl`).',
    "New entries must not use a name from these lists. Use these exact names in a pack's `workshop` to change their",
    'odds or remove them.',
    '',
  ];
  WHEELS.forEach(([k]) => {
    const n = FW.LISTS[k]().length;
    lines.push('- [`' + k + '`: ' + WHEELS.find(w => w[0] === k)[1] + ' (' + n + ')](#' + k + ')');
  });
  lines.push('');
  WHEELS.forEach(([k, title, help]) => {
    lines.push(
      '<a id="' + k + '"></a>',
      '',
      '## `' + k + '`: ' + title,
      '',
      help,
      '',
      '| Name | w | dsl |',
      '| --- | --- | --- |'
    );
    FW.LISTS[k]().forEach(e =>
      lines.push(
        '| ' + e.name.replace(/\|/g, '\\|') + ' | ' + +e.w.toFixed(2) + ' | ' + (e.dsl ? '`' + e.dsl + '`' : '') + ' |'
      )
    );
    lines.push('');
  });
  return lines.join('\n');
}

function generated() {
  const FW = loadGame();
  return { 'reference/theme-variables.md': themeVariables(), 'reference/wheels.md': wheelsReference(FW) };
}

/* ---------------- template 03 sounds (made in code, so they are free to reuse) ---------------- */
const RATE = 22050;
function wav(samples) {
  const data = Buffer.alloc(samples.length * 2);
  samples.forEach((v, i) => data.writeInt16LE(Math.round(Math.max(-1, Math.min(1, v)) * 32767), i * 2));
  const h = Buffer.alloc(44);
  h.write('RIFF', 0);
  h.writeUInt32LE(36 + data.length, 4);
  h.write('WAVE', 8);
  h.write('fmt ', 12);
  h.writeUInt32LE(16, 16);
  h.writeUInt16LE(1, 20);
  h.writeUInt16LE(1, 22);
  h.writeUInt32LE(RATE, 24);
  h.writeUInt32LE(RATE * 2, 28);
  h.writeUInt16LE(2, 32);
  h.writeUInt16LE(16, 34);
  h.write('data', 36);
  h.writeUInt32LE(data.length, 40);
  return Buffer.concat([h, data]);
}
// a music-box note: a sine with a bright overtone and a bell-like decay
function bell(out, start, freq, len, vol) {
  const s0 = Math.round(start * RATE),
    n = Math.round(len * RATE);
  for (let i = 0; i < n && s0 + i < out.length; i++) {
    const t = i / RATE,
      env = Math.min(1, t * 400) * Math.exp(-t * 4.2);
    out[s0 + i] +=
      vol *
      env *
      (Math.sin(2 * Math.PI * freq * t) + 0.32 * Math.sin(2 * Math.PI * freq * 3.01 * t) * Math.exp(-t * 9));
  }
}
const NOTE = n => 440 * Math.pow(2, (n - 69) / 12);
function makeSounds(dir) {
  fs.mkdirSync(dir, { recursive: true });
  const buf = s => new Array(Math.round(s * RATE)).fill(0);
  const tick = buf(0.07);
  bell(tick, 0, NOTE(96), 0.07, 0.35);
  const click = buf(0.09);
  bell(click, 0, NOTE(88), 0.09, 0.3);
  const reveal = buf(1.4);
  [76, 79, 84].forEach((n, i) => bell(reveal, i * 0.09, NOTE(n), 1.3, 0.28));
  const rare = buf(2.2);
  [72, 76, 79, 84, 88, 91].forEach((n, i) => bell(rare, i * 0.08, NOTE(n), 2, 0.22));
  const bad = buf(1.6);
  [64, 61, 57].forEach((n, i) => bell(bad, i * 0.22, NOTE(n), 1.2, 0.3));
  // 8 bars of a gentle waltz (C - Am - F - G, twice) that loops cleanly
  const beat = 0.42,
    bars = [
      [60, 64, 67],
      [57, 60, 64],
      [53, 57, 60],
      [55, 59, 62],
    ];
  const music = buf(beat * 3 * 8);
  for (let b = 0; b < 8; b++) {
    const ch = bars[b % 4],
      t0 = b * beat * 3;
    bell(music, t0, NOTE(ch[0] - 12), beat * 3, 0.18);
    bell(music, t0 + beat, NOTE(ch[1]), beat * 2, 0.12);
    bell(music, t0 + beat, NOTE(ch[2]), beat * 2, 0.12);
    bell(music, t0 + beat * 2, NOTE(ch[1]), beat, 0.12);
    bell(music, t0 + beat * 2, NOTE(ch[2]), beat, 0.12);
    bell(music, t0, NOTE(ch[2] + 12), beat * 1.5, 0.16);
    bell(music, t0 + beat * 1.5, NOTE(ch[1] + 12), beat * 1.5, 0.12);
  }
  const files = {
    'tick.wav': tick,
    'click.wav': click,
    'reveal.wav': reveal,
    'rare.wav': rare,
    'bad.wav': bad,
    'music.wav': music,
  };
  Object.keys(files).forEach(f => fs.writeFileSync(path.join(dir, f), wav(files[f])));
}

/* ---------------- a small zip writer (stored paths, deflate), so the build needs no extra tools ---------------- */
const CRC = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c;
  }
  return t;
})();
const crc32 = b => {
  let c = -1;
  for (let i = 0; i < b.length; i++) c = CRC[(c ^ b[i]) & 0xff] ^ (c >>> 8);
  return (c ^ -1) >>> 0;
};
function zip(entries) {
  // entries: [{ name, data }]
  const parts = [],
    central = [];
  let offset = 0;
  const d = new Date(),
    dosTime = (d.getHours() << 11) | (d.getMinutes() << 5) | (d.getSeconds() >> 1),
    dosDate = ((d.getFullYear() - 1980) << 9) | ((d.getMonth() + 1) << 5) | d.getDate();
  for (const e of entries) {
    const name = Buffer.from(e.name, 'utf8'),
      raw = e.data,
      comp = zlib.deflateRawSync(raw, { level: 9 }),
      crc = crc32(raw);
    const useDeflate = comp.length < raw.length,
      body = useDeflate ? comp : raw;
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(useDeflate ? 8 : 0, 8);
    local.writeUInt16LE(dosTime, 10);
    local.writeUInt16LE(dosDate, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(body.length, 18);
    local.writeUInt32LE(raw.length, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28);
    const cen = Buffer.alloc(46);
    cen.writeUInt32LE(0x02014b50, 0);
    cen.writeUInt16LE(20, 4);
    cen.writeUInt16LE(20, 6);
    cen.writeUInt16LE(0x0800, 8);
    cen.writeUInt16LE(useDeflate ? 8 : 0, 10);
    cen.writeUInt16LE(dosTime, 12);
    cen.writeUInt16LE(dosDate, 14);
    cen.writeUInt32LE(crc, 16);
    cen.writeUInt32LE(body.length, 20);
    cen.writeUInt32LE(raw.length, 24);
    cen.writeUInt16LE(name.length, 28);
    cen.writeUInt32LE(offset, 42);
    parts.push(local, name, body);
    central.push(cen, name);
    offset += local.length + name.length + body.length;
  }
  const cenBuf = Buffer.concat(central),
    end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(cenBuf.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...parts, cenBuf, end]);
}

function walk(dir, base = '') {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap(d => {
      const rel = base ? base + '/' + d.name : d.name;
      return d.isDirectory() ? walk(path.join(dir, d.name), rel) : [rel];
    });
}

function main() {
  const gen = generated();
  if (process.argv.includes('--check')) {
    const stale = Object.keys(gen).filter(f => {
      const p = path.join(kit, f);
      return !fs.existsSync(p) || fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n') !== gen[f];
    });
    if (stale.length) {
      console.error('Out of date: ' + stale.join(', ') + '. Run: node scripts/make-modkit.js');
      process.exit(1);
    }
    console.log('mod kit reference is up to date');
    return;
  }
  Object.keys(gen).forEach(f => {
    fs.mkdirSync(path.dirname(path.join(kit, f)), { recursive: true });
    fs.writeFileSync(path.join(kit, f), gen[f]);
  });
  const snd = path.join(kit, 'templates', '03-sounds', 'sounds');
  if (!fs.existsSync(path.join(snd, 'music.wav')) || process.argv.includes('--sounds')) makeSounds(snd);
  const top = 'DestinyUnbound-ModKit/';
  const files = walk(kit).map(f => ({ name: top + f, data: fs.readFileSync(path.join(kit, f)) }));
  fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
  const out = path.join(root, 'dist', 'DestinyUnbound-ModKit-' + version + '.zip');
  fs.writeFileSync(out, zip(files));
  console.log(
    'wrote ' +
      path.relative(root, out) +
      ' (' +
      files.length +
      ' files, ' +
      (fs.statSync(out).size / 1024).toFixed(0) +
      ' KB)'
  );
}
