function loadGame() {
  if (globalThis.FW && globalThis.FW.LISTS) return globalThis.FW;
  globalThis.window = globalThis;
  const mem = {};
  globalThis.localStorage = {
    getItem: k => (k in mem ? mem[k] : null),
    setItem: (k, v) => {
      mem[k] = String(v);
    },
    removeItem: k => {
      delete mem[k];
    },
  };
  ['data.js', 'engine.js', 'story.js'].forEach(f => require(path.join(root, 'app', 'js', f)));
  return globalThis.FW;
}

