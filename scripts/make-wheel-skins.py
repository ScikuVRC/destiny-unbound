"""Make the painted wheel skins: a rim ring and a hub medallion per theme, cut out of their black backgrounds.

The paintings (art-source/grok-2026-11-16/rim-*.jpg and hub-*.jpg, made with Grok) show the ring or medallion on
pure black. For each one this finds where the artwork starts and ends from the centre outwards, keeps everything in
that band (fully opaque where it is bright, fading to transparent where it fades into black), and clears the rest.
It writes app/art/skins/<theme>-rim.webp and <theme>-hub.webp (with transparency, 768px) and app/js/skins-data.js,
which tells the wheel where each ring's inner and outer edge are.

Usage: python scripts/make-wheel-skins.py   (needs Pillow and numpy)
"""
import json
import os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "art-source", "grok-2026-11-16")
OUT = os.path.join(ROOT, "app", "art", "skins")
SIZE = 768  # rims; hubs are drawn small, so they are saved at half that
PICKS = {
    "ashen": ("rim-ashen-3", "hub-ashen-2"),
    "astral": ("rim-astral-4", "hub-astral-1"),
    "iron": ("rim-iron-3", "hub-iron-3"),
    "bloodmoon": ("rim-bloodmoon-3", "hub-bloodmoon-1"),
    "wild": ("rim-verdant-3", "hub-verdant-1"),  # Verdant Wild (id "wild": the example mod already uses "verdant")
}
FLOOR, CEIL = 0.022, 0.075  # max channel (0..1): below FLOOR is background, above CEIL fully opaque (dark metal stays solid)


def load(name):
    im = Image.open(os.path.join(SRC, name + ".jpg")).convert("RGB")
    a = np.asarray(im).astype(np.float32) / 255.0
    return im, a


def radial(a):
    """Distance of every pixel from the image centre, as a fraction of half the size, and the bright profile."""
    h, w = a.shape[:2]
    yy, xx = np.mgrid[0:h, 0:w]
    r = np.hypot(xx - (w - 1) / 2, yy - (h - 1) / 2) / (min(w, h) / 2)
    m = a.max(axis=2)
    bins = np.clip((r * 200).astype(int), 0, 299)
    bright = np.bincount(bins.ravel(), weights=(m > 0.12).ravel(), minlength=300)
    total = np.bincount(bins.ravel(), minlength=300)
    return r, m, bright / np.maximum(total, 1)


def edges(frac, lo_from=0):
    """Inner and outer radius of the artwork band: where at least 25% of a thin ring of pixels is bright."""
    on = np.where(frac[lo_from:] > 0.25)[0] + lo_from
    return on.min() / 200.0, (on.max() + 1) / 200.0


def cut(a, r, m, lo, hi):
    alpha = np.clip((m - FLOOR) / (CEIL - FLOOR), 0, 1)
    soft = 0.012
    band = np.clip((r - (lo - soft)) / soft, 0, 1) * np.clip(((hi + soft) - r) / soft, 0, 1)
    rgba = np.dstack([a, alpha * band])
    return Image.fromarray((rgba * 255).astype(np.uint8), "RGBA")


def square(im, half, size=SIZE):
    """Crop to the artwork (centre +- half of the half-size), so the ring or hub fills the image, then resize."""
    w, h = im.size
    c = min(w, h) / 2
    box = (round(w / 2 - half * c), round(h / 2 - half * c), round(w / 2 + half * c), round(h / 2 + half * c))
    return im.crop(box).resize((size, size), Image.LANCZOS)


def main():
    os.makedirs(OUT, exist_ok=True)
    data = {}
    for theme, (rim, hub) in PICKS.items():
        # rim: a band from ri to ro
        _, a = load(rim)
        r, m, frac = radial(a)
        ri, ro = edges(frac, lo_from=60)  # ignore anything stray near the centre
        ring = square(cut(a, r, m, ri, ro), ro + 0.01)
        ring.save(os.path.join(OUT, theme + "-rim.webp"), "WEBP", quality=82, method=6)
        # hub: a disc from 0 to rh
        _, a = load(hub)
        r, m, frac = radial(a)
        _, rh = edges(frac)
        disc = square(cut(a, r, m, 0.0, rh), rh + 0.01, SIZE // 2)
        disc.save(os.path.join(OUT, theme + "-hub.webp"), "WEBP", quality=82, method=6)
        # the ring's inner edge as a share of the image's half-size (the image is cropped to ro + 0.01)
        data[theme] = {"inner": round(ri / (ro + 0.01), 4), "outer": round(ro / (ro + 0.01), 4)}
        print(theme, "rim", round(ri, 3), "to", round(ro, 3), "hub to", round(rh, 3))
    with open(os.path.join(ROOT, "app", "js", "skins-data.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write(
            "/* Generated by scripts/make-wheel-skins.py: the painted wheel rims and hubs (art/skins), and where each\n"
            "   ring's inner and outer edge sit, as a share of the image's half-size. */\n"
            "window.FW = window.FW || {};\nFW.SKINS = " + json.dumps(data) + ";\n"
        )


if __name__ == "__main__":
    main()
