// Makes the chapter illustrations the story banner shows (app/art/chapters/<chapter id>.webp) from the picked Grok
// paintings in art-source/grok-2026-11-16 (16:9, made with Grok; prompts in docs/art-credits.md).
// Run: node scripts/make-chapter-art.js   (needs ffmpeg with libwebp on the PATH)
// SPDX-License-Identifier: GPL-3.0-or-later
const { execFileSync } = require('child_process');
const fs = require('fs'),
  path = require('path');
const root = path.join(__dirname, '..');
const SRC = path.join(root, 'art-source', 'grok-2026-11-16');
const OUT = path.join(root, 'app', 'art', 'chapters');
// chapter id (app/js/story.js) -> picked painting
const PICKS = {
  train: 'ch-train-4',
  study: 'ch-study-4',
  nemesis: 'ch-nemesis-2',
  dungeon: 'ch-dungeon-4',
  quest: 'ch-quest-2',
  treasure: 'ch-treasure-1',
  timeSkip: 'ch-timeskip-2',
  kingdom: 'ch-kingdom-1',
  duel: 'ch-duel-2',
  artifact: 'ch-artifact-4',
  boss: 'ch-boss-2',
  siege: 'ch-siege-1',
};
fs.mkdirSync(OUT, { recursive: true });
for (const [id, pick] of Object.entries(PICKS)) {
  const src = path.join(SRC, pick + '.jpg');
  if (!fs.existsSync(src)) throw new Error('missing ' + src);
  execFileSync('ffmpeg', [
    '-y',
    '-loglevel',
    'error',
    '-i',
    src,
    '-vf',
    'scale=960:-2',
    '-c:v',
    'libwebp',
    '-quality',
    '78',
    path.join(OUT, id + '.webp'),
  ]);
}
fs.writeFileSync(
  path.join(root, 'app', 'js', 'chapter-art.js'),
  '/* Generated by scripts/make-chapter-art.js: chapters that have a painted illustration (art/chapters/<id>.webp). */\nwindow.FW = window.FW || {};\nFW.CHAPTER_ART = ' +
    JSON.stringify(Object.keys(PICKS)) +
    ';\n'
);
console.log('wrote ' + Object.keys(PICKS).length + ' chapter illustrations');
