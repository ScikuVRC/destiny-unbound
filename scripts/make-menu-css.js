// Builds app/css/menu.css (the themed title screens) and app/js/menu-data.js from the approved mockup
// designs in mockups/menu/_gen-art.js, and copies the painted art into app/art.
// Run: node scripts/make-menu-css.js
// SPDX-License-Identifier: GPL-3.0-or-later
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const { T, LOGO, ICON } = require(path.join(root, 'mockups', 'menu', '_gen-art.js'));
const LOOKS = ['ashen', 'astral', 'iron', 'bloodmoon'];

/* prefix every selector of a flat stylesheet (no nested blocks) with a scope */
function scope(css, pre) {
  return css.replace(/\/\*[\s\S]*?\*\//g, '').split('}').map(r => r.trim()).filter(Boolean).map(rule => {
    const i = rule.indexOf('{'); if (i < 0) return '';
    const sels = rule.slice(0, i).split(',').map(s => s.trim()).filter(Boolean).map(s => pre + ' ' + s).join(',');
    return sels + '{' + rule.slice(i + 1) + '}';
  }).join('\n');
}
const fixUrls = css => css.replace(/url\(art\//g, 'url(../art/');

let out = `/* Destiny Unbound title screens: one painted look per theme. Generated by scripts/make-menu-css.js from
   mockups/menu/_gen-art.js - edit the designs there, then run the script. */
#screen-title{position:fixed;inset:0;z-index:20;overflow:hidden;background:#000;padding:0;max-width:none}
body.on-title .top{display:none}
.tscr{position:absolute;inset:0;font-family:var(--font)}
.tscr .bgart{position:absolute;inset:0}
.tscr .fxlayer{position:absolute;inset:0;pointer-events:none}
.tscr .stage{position:absolute;left:0;top:0;width:1280px;height:720px}   /* scaled and centred with zoom by menu.js: a transform would cut the painted art off from the background it blends into */
.tscr .wheelart,.tscr .title,.tscr .panel{position:absolute}
.tscr .title h2{margin:0}.tscr .title p{margin:0}
.tscr .panel{margin:0;list-style:none}
.tscr .item{display:flex;align-items:center;width:100%;background:none;border:0;font:inherit;color:inherit;text-align:left;cursor:pointer;-webkit-appearance:none;appearance:none}
.tscr .item:focus{outline:none}.tscr .item:focus-visible{outline:2px solid currentColor;outline-offset:2px}
.tscr .item[hidden]{display:none}
.tscr .item .ic{flex:none}
.tscr .foot{position:absolute;left:0;right:0;bottom:0;display:flex;justify-content:space-between;align-items:center;gap:12px;padding:12px 22px;font-size:13px;z-index:2}
.tscr .foot span{opacity:.8}.tscr .foot b{font-weight:600}
.tscr .foot button{background:none;border:0;color:inherit;font:inherit;cursor:pointer;padding:2px 6px;opacity:.85}.tscr .foot button:hover{opacity:1;text-decoration:underline}
.tscr .foot .links{display:flex;gap:6px;align-items:center}
.tscr .title h2.logoart{display:block;margin:0 auto;width:100%;color:transparent!important;font-size:0!important;-webkit-background-clip:border-box!important;background-clip:border-box!important;filter:none!important;text-shadow:none!important;-webkit-mask:radial-gradient(closest-side,#000 86%,transparent);mask:radial-gradient(closest-side,#000 86%,transparent)}
.tscr .title .crest{display:none}
`;
for (const k of LOOKS) {
  const t = T[k], L = LOGO[k], pre = '.tscr[data-look="' + k + '"]';
  const blend = 'screen';
  out += '\n/* ---- ' + k + ' ---- */\n' + fixUrls(scope(t.css, pre)) + '\n';
  out += pre + ' .title h2.logoart{height:' + L.h + 'px;background:url(../art/' + k + '-logo.jpg) center/' + L.zoom + '% auto no-repeat;mix-blend-mode:' + blend + '}\n';
  if (L.css) out += scope(L.css, pre) + '\n';
}
// the decorative layers in the mockups (embers, stars) were sized for the 1280x720 screen; here they cover the window
out += `
.tscr .embers,.tscr .stars{position:absolute;inset:0;pointer-events:none}
/* opening animation */
.tscr .stage .title,.tscr .stage .panel{animation:tIn .7s ease backwards}.tscr .stage .panel{animation-delay:.12s}
@keyframes tIn{from{opacity:0}}
.tscr[data-look] .stage .wheelart{animation:tWheel 1.4s ease both}
@keyframes tWheel{from{opacity:0}}
body.anim-off .tscr .stage>*,body.anim-reduced .tscr .stage>*{animation:none}
body.no-glow .tscr .embers,body.no-glow .tscr .stars{display:none}
/* tall or narrow windows (phones): a simple stacked menu instead of the painted layout */
@media (max-aspect-ratio:1/1){
  .tscr .stage{position:relative;left:auto!important;top:auto!important;zoom:1!important;width:auto;height:auto;display:flex;flex-direction:column;align-items:center;padding:24px 16px 80px;min-height:100%;overflow:auto}
  .tscr .wheelart{display:none}
  .tscr .title,.tscr .panel{position:relative!important;left:auto!important;right:auto!important;top:auto!important;transform:none!important;margin:0 auto!important;width:100%!important;max-width:420px;height:auto!important}
  .tscr .title h2.logoart{height:150px!important}
  .tscr .panel{margin-top:14px!important}
}
`;
fs.writeFileSync(path.join(root, 'app', 'css', 'menu.css'), out);
fs.writeFileSync(path.join(root, 'app', 'js', 'menu-data.js'), '/* Generated by scripts/make-menu-css.js: menu icons and taglines for the title screens. */\nwindow.FW = window.FW || {};\nFW.MENU_ICONS = ' + JSON.stringify(ICON) + ';\nFW.MENU_TAGS = ' + JSON.stringify(Object.fromEntries(LOOKS.map(k => [k, T[k].tag]))) + ';\n');
fs.mkdirSync(path.join(root, 'app', 'art'), { recursive: true });
for (const k of LOOKS) for (const p of ['bg', 'wheel', 'logo']) fs.copyFileSync(path.join(root, 'mockups', 'menu', 'art', k + '-' + p + '.jpg'), path.join(root, 'app', 'art', k + '-' + p + '.jpg'));
console.log('wrote app/css/menu.css, app/js/menu-data.js and copied 12 images to app/art');
